# ── 11. State-wise summary ────────────────────────────────────────────────────
def statewise_summary(out):
    section("STATE-WISE PREDICTION SUMMARY")
    states = out.groupby("state").apply(
        lambda g: pd.Series({
            "Locations": len(g),
            "FloodHigh": (g["flood_risk"] == "High").sum(),
            "FloodMed":  (g["flood_risk"] == "Medium").sum(),
            "LSHigh":    (g["landslide_risk"] == "High").sum(),
            "LSMed":     (g["landslide_risk"] == "Medium").sum(),
        })
    ).reset_index()
    states = states.sort_values("Locations", ascending=False)
    print(f"  {'State':<25} {'Locs':>5} {'FloodH':>7} {'FloodM':>7} {'LSHigh':>7} {'LSMed':>7}")
    print(DIV2)
    for _, r in states.iterrows():
        print(f"  {r['state']:<25} {int(r['Locations']):>5} {int(r['FloodHigh']):>7} "
              f"{int(r['FloodMed']):>7} {int(r['LSHigh']):>7} {int(r['LSMed']):>7}")

