# ── 1. Check model files exist ────────────────────────────────────────────────
def check_model_files():
    missing = []
    for p, name in [(FLOOD_MODEL_PATH, "flood_model.pkl"),
                    (LS_MODEL_PATH,    "landslide_model.pkl")]:
        if not os.path.exists(p):
            missing.append(name)
    if missing:
        raise FileNotFoundError(
            f"Model file(s) missing: {missing}\n"
            "Train the flood and landslide models first:\n"
            "  python ml/train_flood.py\n"
            "  python ml/train_landslide.py"
        )

# ── 2. Load model bundles ─────────────────────────────────────────────────────
def load_models():
    section("LOADING MODEL BUNDLES")
    flood_bundle = joblib.load(FLOOD_MODEL_PATH)
    ls_bundle    = joblib.load(LS_MODEL_PATH)
    print(f"  Flood    bundle loaded : {FLOOD_MODEL_PATH}")
    print(f"  Flood    features      : {flood_bundle['features']}")
    print(f"  Flood    target        : {flood_bundle['target']}")
    print(f"  Flood    data_type     : {flood_bundle['data_type']}")
    print()
    print(f"  Landslide bundle loaded : {LS_MODEL_PATH}")
    print(f"  Landslide features      : {ls_bundle['features']}")
    print(f"  Landslide target        : {ls_bundle['target']}")
    print(f"  Landslide data_type     : {ls_bundle['data_type']}")
    return flood_bundle, ls_bundle

# ── 3. Load dataset + validate features ──────────────────────────────────────
def load_data(flood_bundle, ls_bundle):
    section("LOADING DATASET & VALIDATING FEATURES")
    if not os.path.exists(DATA_PATH):
        raise FileNotFoundError(f"Dataset not found: {DATA_PATH}\nRun: python ml/prepare_data.py")
    df = pd.read_csv(DATA_PATH)
    print(f"  Loaded : {DATA_PATH}")
    print(f"  Rows   : {len(df)}")
    print(f"  Cols   : {list(df.columns)}")

    # Validate flood features
    missing_f = [c for c in flood_bundle["features"] if c not in df.columns]
    if missing_f:
        raise ValueError(f"[FLOOD] Required features missing from dataset: {missing_f}")
    print(f"\n  Flood feature check    : PASSED {flood_bundle['features']}")

    # Validate landslide features
    missing_l = [c for c in ls_bundle["features"] if c not in df.columns]
    if missing_l:
        raise ValueError(f"[LANDSLIDE] Required features missing from dataset: {missing_l}")
    print(f"  Landslide feature check: PASSED {ls_bundle['features']}")

    # Missing values in any feature column
    all_feat_cols = list(set(flood_bundle["features"] + ls_bundle["features"]))
    mv = df[all_feat_cols].isnull().sum()
    mv_found = mv[mv > 0]
    if not mv_found.empty:
        print(f"\n  [WARNING] Missing values in feature columns:\n{mv_found.to_string()}")
    else:
        print("  Missing value check    : NONE FOUND - OK")
    return df

# ── 4. Coordinate validation ──────────────────────────────────────────────────
def validate_coordinates(df):
    section("COORDINATE VALIDATION")
    bad_lat = df[(df["latitude"] < -90)  | (df["latitude"] > 90)]
    bad_lon = df[(df["longitude"] < -180) | (df["longitude"] > 180)]
    if bad_lat.empty and bad_lon.empty:
        print("  All coordinates in valid range  : PASSED")
        print(f"  Latitude  range : {df['latitude'].min():.4f} to {df['latitude'].max():.4f}")
        print(f"  Longitude range : {df['longitude'].min():.4f} to {df['longitude'].max():.4f}")
    else:
        if not bad_lat.empty:
            print(f"  [ERROR] Invalid latitudes:\n{bad_lat[['district','state','latitude']].to_string()}")
        if not bad_lon.empty:
            print(f"  [ERROR] Invalid longitudes:\n{bad_lon[['district','state','longitude']].to_string()}")

# ── 5. Duplicate check ────────────────────────────────────────────────────────
def check_duplicates(df):
    section("DUPLICATE LOCATION CHECK")
    dupes = df[df.duplicated(subset=["district","state"], keep=False)]
    if dupes.empty:
        print("  No duplicate district+state combinations found  : PASSED")
    else:
        print(f"  [WARNING] {len(dupes)} duplicate district+state rows:")
        print(dupes[["district","state"]].to_string(index=True))
    return df.drop_duplicates(subset=["district","state"]).reset_index(drop=True)

# ── 6. Generate predictions ───────────────────────────────────────────────────
def generate_predictions(df, flood_bundle, ls_bundle):
    section("GENERATING PREDICTIONS")
    flood_model    = flood_bundle["model"]
    flood_features = flood_bundle["features"]
    ls_model       = ls_bundle["model"]
    ls_features    = ls_bundle["features"]

    print("  Running flood model predictions ...")
    X_flood = df[flood_features].values
    flood_pred  = flood_model.predict(X_flood)
    flood_proba = flood_model.predict_proba(X_flood)   # shape (n, n_classes)
    flood_cls   = list(flood_model.classes_)            # e.g. ['High','Low','Medium'] — order from model

    print(f"  Flood model classes order : {flood_cls}")
    print(f"  Flood predictions done    : {len(flood_pred)} rows")

    print()
    print("  Running landslide model predictions ...")
    X_ls    = df[ls_features].values
    ls_pred  = ls_model.predict(X_ls)
    ls_proba = ls_model.predict_proba(X_ls)
    ls_cls   = list(ls_model.classes_)

    print(f"  Landslide model classes order : {ls_cls}")
    print(f"  Landslide predictions done    : {len(ls_pred)} rows")

    # ── Build output dataframe ────────────────────────────────────────────────
    out = df.copy()

    # Rename source labels
    out["source_flood_risk"]     = df["flood_risk"]
    out["source_landslide_risk"] = df["landslide_risk"]

    # ── Flood columns ─────────────────────────────────────────────────────────
    out["flood_risk"] = flood_pred

    # Probability columns — use model.classes_ for safe mapping
    flood_proba_df = pd.DataFrame(
        flood_proba,
        columns=[f"_fp_{c.lower()}" for c in flood_cls]
    )
    # Map to standard names using actual class labels
    def get_prob_col(proba_df, cls_list, target_class):
        col = f"_fp_{target_class.lower()}"
        if col in proba_df.columns:
            return proba_df[col].values
        return np.zeros(len(proba_df))

    f_low  = get_prob_col(flood_proba_df, flood_cls, "Low")
    f_med  = get_prob_col(flood_proba_df, flood_cls, "Medium")
    f_high = get_prob_col(flood_proba_df, flood_cls, "High")

    out["flood_prob_low"]    = np.round(f_low  * 100, 2)
    out["flood_prob_medium"] = np.round(f_med  * 100, 2)
    out["flood_prob_high"]   = np.round(f_high * 100, 2)

    # flood_probability = probability of the predicted class
    pred_flood_probs = []
    for pred_class, row_proba in zip(flood_pred, flood_proba):
        idx = flood_cls.index(pred_class)
        pred_flood_probs.append(round(float(row_proba[idx]) * 100, 2))
    out["flood_probability"] = pred_flood_probs

    # ── Landslide columns ─────────────────────────────────────────────────────
    out["landslide_risk"] = ls_pred

    ls_proba_df = pd.DataFrame(
        ls_proba,
        columns=[f"_lp_{c.lower()}" for c in ls_cls]
    )
    def get_ls_prob_col(proba_df, cls_list, target_class):
        col = f"_lp_{target_class.lower()}"
        if col in proba_df.columns:
            return proba_df[col].values
        return np.zeros(len(proba_df))

    l_low  = get_ls_prob_col(ls_proba_df, ls_cls, "Low")
    l_med  = get_ls_prob_col(ls_proba_df, ls_cls, "Medium")
    l_high = get_ls_prob_col(ls_proba_df, ls_cls, "High")

    out["landslide_prob_low"]    = np.round(l_low  * 100, 2)
    out["landslide_prob_medium"] = np.round(l_med  * 100, 2)
    out["landslide_prob_high"]   = np.round(l_high * 100, 2)

    pred_ls_probs = []
    for pred_class, row_proba in zip(ls_pred, ls_proba):
        idx = ls_cls.index(pred_class)
        pred_ls_probs.append(round(float(row_proba[idx]) * 100, 2))
    out["landslide_probability"] = pred_ls_probs

    return out

# ── 7. Probability validation ─────────────────────────────────────────────────
def validate_probabilities(out):
    section("PROBABILITY VALIDATION")

    f_sum = out["flood_prob_low"] + out["flood_prob_medium"] + out["flood_prob_high"]
    l_sum = out["landslide_prob_low"] + out["landslide_prob_medium"] + out["landslide_prob_high"]

    f_ok = np.allclose(f_sum.values, 100.0, atol=0.5)
    l_ok = np.allclose(l_sum.values, 100.0, atol=0.5)

    print(f"  Flood probability sums    : min={f_sum.min():.2f}  max={f_sum.max():.2f}  "
          f"valid={'PASSED' if f_ok else 'FAILED'}")
    print(f"  Landslide probability sums: min={l_sum.min():.2f}  max={l_sum.max():.2f}  "
          f"valid={'PASSED' if l_ok else 'FAILED'}")

    if not f_ok:
        bad = out[~np.isclose(f_sum, 100.0, atol=0.5)][["district","state"]]
        print(f"  [ERROR] Flood probability sums off:\n{bad.to_string()}")
    if not l_ok:
        bad = out[~np.isclose(l_sum, 100.0, atol=0.5)][["district","state"]]
        print(f"  [ERROR] Landslide probability sums off:\n{bad.to_string()}")

    # Range check
    for col in ["flood_prob_low","flood_prob_medium","flood_prob_high",
                "landslide_prob_low","landslide_prob_medium","landslide_prob_high"]:
        if (out[col] < 0).any() or (out[col] > 100).any():
            print(f"  [ERROR] Out-of-range probability in column: {col}")
        
    print("  All probabilities in [0,100] range : PASSED")

# ── 8. Predicted class consistency check ──────────────────────────────────────
def validate_class_consistency(out):
    section("PREDICTED CLASS CONSISTENCY CHECK")
    CLASS_ORDER = ["Low", "Medium", "High"]

    def max_class(row, prefix):
        probs = {c: row[f"{prefix}_prob_{c.lower()}"] for c in CLASS_ORDER}
        return max(probs, key=probs.get)

    flood_max = out.apply(lambda r: max_class(r, "flood"), axis=1)
    ls_max    = out.apply(lambda r: max_class(r, "landslide"), axis=1)

    flood_ok = (out["flood_risk"] == flood_max).all()
    ls_ok    = (out["landslide_risk"] == ls_max).all()

    print(f"  Flood predicted class matches max probability    : {'PASSED' if flood_ok else 'FAILED'}")
    print(f"  Landslide predicted class matches max probability: {'PASSED' if ls_ok else 'FAILED'}")

    if not flood_ok:
        bad = out[out["flood_risk"] != flood_max][["district","state","flood_risk"]]
        print(f"  [ERROR] Flood class mismatch rows:\n{bad.to_string()}")
    if not ls_ok:
        bad = out[out["landslide_risk"] != ls_max][["district","state","landslide_risk"]]
        print(f"  [ERROR] Landslide class mismatch rows:\n{bad.to_string()}")

