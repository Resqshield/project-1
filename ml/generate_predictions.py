# ── 14. Interesting risk combinations ─────────────────────────────────────────
def risk_combinations(out):
    section("INTERESTING FLOOD / LANDSLIDE RISK COMBINATIONS")
    combos = [
        ("High Flood + Low Landslide",    "High",   "Low"),
        ("High Flood + High Landslide",   "High",   "High"),
        ("Low Flood  + High Landslide",   "Low",    "High"),
        ("Low Flood  + Low Landslide",    "Low",    "Low"),
        ("Medium Flood + High Landslide", "Medium", "High"),
    ]
    for label, fr, lr in combos:
        mask = (out["flood_risk"] == fr) & (out["landslide_risk"] == lr)
        subset = out[mask]
        print(f"\n  {label.upper()} ({len(subset)} locations)")
        if subset.empty:
            print("    No location currently matches this combination.")
        else:
            for _, r in subset.head(3).iterrows():
                print(f"    {r['district']}, {r['state']}  |  "
                      f"Flood: {r['flood_risk']} {r['flood_probability']:.1f}%  |  "
                      f"Landslide: {r['landslide_risk']} {r['landslide_probability']:.1f}%")

# ── 15. Save outputs ──────────────────────────────────────────────────────────
def save_outputs(out):
    section("SAVING OUTPUTS")
    os.makedirs(PRED_DIR, exist_ok=True)

    # Build final dataframe with only output columns
    final = out[OUTPUT_COLS].copy()

    # Save CSV
    final.to_csv(CSV_OUT, index=False)
    print(f"  CSV saved  : {CSV_OUT}")
    print(f"  Rows       : {len(final)}")
    print(f"  Columns    : {len(final.columns)}")

    # Save JSON (records orientation, rounded floats)
    json_records = []
    for _, r in final.iterrows():
        record = {}
        for col in OUTPUT_COLS:
            val = r[col]
            if isinstance(val, (np.floating, float)):
                record[col] = round(float(val), 4)
            elif isinstance(val, (np.integer, int)):
                record[col] = int(val)
            else:
                record[col] = val
        json_records.append(record)

    with open(JSON_OUT, "w", encoding="utf-8") as f:
        json.dump(json_records, f, indent=2, ensure_ascii=False)
    print(f"  JSON saved : {JSON_OUT}")

    print()
    print("  [!] DISCLAIMER: SYNTHETIC/DEMO MODEL PREDICTIONS.")
    print("      Not real-world early-warning forecasts.")
    return final

